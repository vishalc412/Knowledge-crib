/**
 * docs-site-check — the M4.4 "docs site + stats drift" gate.
 *
 * Pins the plan's M4.4 gate intent: "site builds; one canonical stats source." Two failure modes
 * this gate exists to catch:
 *
 *   (a) STATS DRIFT — someone hand-edits `docs/STATS.md`, or adds a package/language/test and
 *       forgets to re-run `pnpm docs:stats`. The committed file then lags the real tree. Gate
 *       regenerates and asserts byte-identical via `git diff --exit-code` (a generated-file
 *       freshness check — no temp file, no env override; the regen output IS the comparison).
 *
 *   (b) PROSE DRIFT RECURS — `docs/README.md` used to hardcode "392 tests green, 7-language deep
 *       extraction"; both went stale (suite ~10x larger, PHP added). The fix is to de-hardcode and
 *       reference STATS.md. Gate asserts the stale hardcodes are GONE and the STATS.md reference is
 *       PRESENT, so a future edit that re-introduces a hardcoded number in prose fails the gate.
 *
 *   (c) SITE FRESHNESS — `docs/site/index.html` is generated by `docs-site-build.mjs` from
 *       STATS.md + docs/README.md. Gate rebuilds it and asserts the canonical parser-language
 *       count (parsed from STATS.md) appears in the rendered site, so a stale site that predates a
 *       language addition is caught. (A byte-diff on the site is over-constraining — the gate only
 *       needs the site to carry the current canonical numbers.)
 *
 * Run order: regenerate STATS → drift-check it → rebuild site → assert site carries current
 * numbers → assert docs/README.md de-hardcoded. Every assertion prints a ✓/fail line. Exit 1 on
 * any fail so release:verify stops.
 *
 * release:verify builds every package before any gate runs; this gate only touches docs/ + git, so
 * no build dependency.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, '..');
const DOCS = join(REPO, 'docs');

let failed = 0;
const pass = (msg) => process.stdout.write(`  docs-site:check — ${msg}\n`);
const fail = (msg) => {
  process.stderr.write(`  docs-site:check FAIL — ${msg}\n`);
  failed++;
};

const node = (args, opts = {}) => {
  try {
    return execFileSync(process.execPath, args, {
      cwd: REPO,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      ...opts,
    });
  } catch (err) {
    return null;
  }
};

// --- (a) regenerate STATS.md, then assert the committed copy is byte-identical (no drift) -----
node(['scripts/docs-stats.mjs']);
let driftExit = 0;
try {
  execFileSync('git', ['diff', '--exit-code', '--', 'docs/STATS.md'], {
    cwd: REPO,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
} catch (err) {
  driftExit = err.status ?? 1;
}
if (driftExit === 0) pass('docs/STATS.md is fresh (regen == committed, no drift)');
else fail('docs/STATS.md drifted — re-run `pnpm docs:stats` and commit the regenerated file');

// --- parse the canonical numbers out of the (now-regenerated) STATS.md ----------------------
const stats = readFileSync(join(DOCS, 'STATS.md'), 'utf8');
const parserLangCount = stats.match(/^\|\s*parser languages\s*\|\s*(\d+)/m)?.[1];
const pkgCount = stats.match(/^\|\s*packages\s*\|\s*(\d+)/m)?.[1];
if (!parserLangCount || !pkgCount)
  fail('could not parse parser-languages / packages counts from STATS.md');

// --- (b) docs/README.md de-hardcoded: stale hardcodes GONE, STATS.md reference PRESENT -------
const readme = readFileSync(join(DOCS, 'README.md'), 'utf8');
if (/392\s*tests/.test(readme))
  fail('docs/README.md still hardcodes "392 tests" (stale — remove + reference STATS.md)');
else pass('docs/README.md no longer hardcodes "392 tests"');
if (/7-language\s+deep\s+extraction/.test(readme))
  fail(
    'docs/README.md still hardcodes "7-language deep extraction" (stale — remove + reference STATS.md)',
  );
else pass('docs/README.md no longer hardcodes "7-language deep extraction"');
if (/STATS\.md/.test(readme)) pass('docs/README.md references STATS.md (canonical stats source)');
else
  fail(
    'docs/README.md does not reference STATS.md — the de-hardcode must point readers at the canonical source',
  );

// --- (c) rebuild the site, assert it carries the current canonical numbers ------------------
node(['scripts/docs-site-build.mjs']);
const site = join(DOCS, 'site', 'index.html');
if (!existsSync(site)) {
  fail('docs-site-build.mjs did not produce docs/site/index.html');
} else {
  const html = readFileSync(site, 'utf8');
  if (
    html.includes(`>${pkgCount} `) ||
    html.includes(`>${parserLangCount} `) ||
    new RegExp(`\\b${parserLangCount}\\b`).test(html)
  ) {
    pass(`site index embeds canonical parser-langs count (${parserLangCount})`);
  } else {
    fail(
      `site index does not embed the canonical parser-langs count (${parserLangCount}) — rebuild is stale`,
    );
  }
  if (/scripts\/docs-site-build\.mjs/.test(html))
    pass('site index credits its generator (anti-hand-edit marker)');
  else fail('site index missing the generator marker — hand-edited or stale build');
  if (/\.\.\/README\.md/.test(html))
    pass('site index links back to docs/README.md (curated nav source)');
  else fail('site index does not link back to docs/README.md');
}

if (failed > 0) {
  process.stderr.write(`\ndocs-site:check — ${failed} assertion(s) failed\n`);
  process.exit(1);
}
process.stdout.write('\ndocs-site:check — all assertions passed\n');
